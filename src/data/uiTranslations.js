/**
 * Helper to safely get translated string with English/Hindi fallback
 */
export function getUIText(category, key, langId = 'en') {
  const cat = UI_TRANSLATIONS[category];
  if (!cat) return "";
  const item = cat[key];
  if (!item) return "";
  return item[langId] || item.hi || item.en || "";
}

/**
 * Detect language from spoken voice transcript
 * Handles variations e.g., if user says "Bengali", "bangla", "বাংলা", "I speak Hindi", "Tamil please"
 */
export function detectLanguageFromVoice(transcript = '', languagesList = []) {
  if (!transcript || typeof transcript !== 'string') return null;
  const t = transcript.toLowerCase().trim();

  // Exhaustive keyword mappings for each language ID
  const patterns = {
    bn: ['bengali', 'bangla', 'বাংলা', 'বাঙালি', 'বঙ্গ', 'bengal', 'bangali', 'bongali'],
    hi: ['hindi', 'हिन्दी', 'हिंदी', 'hindustani', 'hind', 'hndi'],
    en: ['english', 'inglish', 'अंग्रेजी', 'ইংরেজি', 'ஆங்கிலம்', 'ఇంగ్లీష్', 'angreji', 'angrezi'],
    ta: ['tamil', 'தமிழ்', 'tamizh', 'tamila', 'thamil'],
    te: ['telugu', 'తెలుగు', 'telgu'],
    mr: ['marathi', 'मराठी', 'maratha'],
    gu: ['gujarati', 'ગુજરાતી', 'gujrati', 'gujrat'],
    kn: ['kannada', 'ಕನ್ನಡ', 'kanada', 'kannad'],
    ml: ['malayalam', 'മലയാളം', 'malyalam'],
    pa: ['punjabi', 'ਪੰਜਾਬੀ', 'पंजाबी', 'panjabi', 'punjab'],
    or: ['odia', 'oriya', 'oria', 'ଓଡ଼ିଆ', 'उड़िया'],
    as: ['assamese', 'অসমীয়া', 'asomiya', 'assam', 'axomiya'],
    ur: ['urdu', 'اردو', 'उर्दू'],
    mai: ['maithili', 'मैथिली'],
    sa: ['sanskrit', 'संस्कृतम्', 'संस्कृत'],
    ne: ['nepali', 'नेपाली'],
    kok: ['konkani', 'कोंकणी'],
    sd: ['sindhi', 'سنڌي', 'सिंधी'],
    ks: ['kashmiri', 'کٲشُر', 'कॉशुर', 'कश्मीरी'],
    dgo: ['dogri', 'डोगरी'],
    mni: ['manipuri', 'মৈতৈলোন্', 'মণিপুরী', 'meitei'],
    brx: ['bodo', 'बड़ो', 'boro'],
    sat: ['santali', 'ᱥᱟᱱᱛᱟᱲᱤ', 'संथाली']
  };

  for (const [langId, keywords] of Object.entries(patterns)) {
    for (const kw of keywords) {
      if (t.includes(kw.toLowerCase())) {
        return languagesList.find(l => l.id === langId) || null;
      }
    }
  }

  // Fallback check against nativeName and English name directly
  return languagesList.find(l => 
    t.includes(l.name.toLowerCase()) || 
    t.includes(l.nativeName.toLowerCase())
  ) || null;
}
